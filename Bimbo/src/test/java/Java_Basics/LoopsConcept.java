package Java_Basics;

public class LoopsConcept {

	public static void main(String[] args) {

		//1. While loop
		
		//print 1 to 10 
		
		int i=1;
		
		 while(i<=10)
		 {
			 System.out.println(i);
			 i=i+1;
		 }	
		 
		 System.out.println("*************");
		 //2. For Loop
		 
		 for(int j=1; j<=10; j++)
		 {
			 System.out.println(j);
		 }
		 
		 System.out.println("*************");

		 
		//print 10 to 1 
			
			int k=10;
			
			 while(k>=1)
			 {
				 System.out.println(k);
				 k=k-1;
			 }	
			 
			 System.out.println("*************");
			 //2. For Loop
			 
			 for(int l=10; l>=1; l--)
			 {
				 System.out.println(l);
			 }
		
	}

}
