package Java_Basics;

public class DataTypes {
	
	public static void main (String[] args)
	{
		//Premetive datatypes.
		//1. int
		
		int i=10;
		i=20;
		int j=20;
		int r=-1;
		
		System.out.println(r);
		//2. double
		
		double k=10.16;
		double l=12.00;
		System.out.println(l);

		//3 char it's single character written within the single quotes
	
		char c='A';
		char d='v';
		
		//4. Boolean
		
		Boolean b1=true;
		Boolean b2=false;
		
		//5. String is a class not data Type.
		
		String a="Danesh";
		String a1="This is my Java code";
		
		System.out.println(a1);
		
		System.out.println(i+j);
		System.out.println(i-j);
		System.out.println(i*j);
		System.out.println(i/j);


	}

}
