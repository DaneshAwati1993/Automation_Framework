package Core_Java;

public class StringConacatingArithmaticOperations {

	public static void main(String[] args) {
		
		//Arithmatic Operations + - * /
		System.out.println("Java"+10+20);
		System.out.println(10+20+"Java"+10+50);
		
		System.out.println("Java"+(100-20));
		System.out.println(100-50+"Java"+(100-20));
		
		System.out.println("Java"+10*20);
		System.out.println(10*50+"Java"+10*20);
		
		System.out.println("Java"+10/2);
		System.out.println(10/50+"Java"+100/20);
		
		System.out.println("Java"+10%3);
		System.out.println(100%30+"Java"+100%20);

	}

}
